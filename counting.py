#pg. 122 Introducing While Loops
#the FOR LOOP = taking collection of items and executing a block of code once for each item in collection
#in contrast: WHILE loop runs as long as, or 'while', a certain condition is TRUE

current_number = 1		#start counting from 1 by setting value of current_number to 1
while current_number <= 5:				#while loop is set to keep running as long as the value of current_number is less than or equal to 5
	print(current_number)		
	current_number +=1

#a game needs a while loop to keep running as long as you want to keep playing, and so it can stop running as soon as you ask it to quit
